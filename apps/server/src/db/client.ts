import { mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { PGlite } from '@electric-sql/pglite';
import type { PgDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core';
import { drizzle as drizzleNodePg } from 'drizzle-orm/node-postgres';
import { migrate as migrateNodePg } from 'drizzle-orm/node-postgres/migrator';
import { drizzle as drizzlePglite } from 'drizzle-orm/pglite';
import { migrate as migratePglite } from 'drizzle-orm/pglite/migrator';
import pg from 'pg';

import { acquirePgliteLock } from './pglite-lock';
import * as schema from './schema';

/** SQL migrations generated by drizzle-kit (`pnpm --filter @after-hours/server db:generate`). */
export const MIGRATIONS_DIR = fileURLToPath(new URL('../../drizzle', import.meta.url));

/** Driver-agnostic Drizzle handle used by every query module. */
export type Db = PgDatabase<PgQueryResultHKT, typeof schema>;

export type DatabaseTarget =
  /** Hosted Postgres (Supabase session pooler URI). */
  | { kind: 'postgres'; url: string }
  /** In-process Postgres. `dataDir` undefined: in memory (tests). */
  | { kind: 'pglite'; dataDir?: string };

export interface Database {
  db: Db;
  target: DatabaseTarget['kind'];
  migrate(): Promise<void>;
  close(): Promise<void>;
}

export function openDatabase(target: DatabaseTarget): Database {
  if (target.kind === 'postgres') {
    const pool = new pg.Pool({ connectionString: target.url, max: 5 });
    const db = drizzleNodePg(pool, { schema });
    return {
      db: db as unknown as Db,
      target: 'postgres',
      migrate: () => migrateNodePg(db, { migrationsFolder: MIGRATIONS_DIR }),
      close: () => pool.end(),
    };
  }
  let release = () => {};
  if (target.dataDir) {
    mkdirSync(target.dataDir, { recursive: true });
    release = acquirePgliteLock(target.dataDir);
  }
  const client = new PGlite(target.dataDir);
  const db = drizzlePglite(client, { schema });
  return {
    db: db as unknown as Db,
    target: 'pglite',
    migrate: () => migratePglite(db, { migrationsFolder: MIGRATIONS_DIR }),
    close: async () => {
      await client.close();
      release();
    },
  };
}
